// Embeds the CP/M test ROMs in tests/roms as hex strings in tests/RomData.elm.
// elm-test cannot read files, so the ROM bytes have to live in an Elm module.
// Run with: npm run gen:roms
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const roms = [
    { name: 'tst8080', file: 'TST8080.COM', comment: 'TST8080.COM, Microcosm 8080/8085 CPU diagnostic' },
    { name: 'prelim8080', file: '8080PRE.COM', comment: '8080PRE.COM, preliminary 8080 tests' },
    { name: 'cputest', file: 'CPUTEST.COM', comment: 'CPUTEST.COM, Supersoft diagnostics II CPU test' },
    { name: 'exerciser8080', file: '8080EXM.COM', comment: '8080EXM.COM, CRC based 8080 instruction exerciser' },
];

const lines = [
    'module RomData exposing (cputest, exerciser8080, prelim8080, tst8080)',
    '',
    '{-| Generated by scripts/generate-rom-data.mjs from tests/roms. Do not edit by hand.',
    '',
    'Each value is the raw bytes of a CP/M .COM file as a hex string (two characters per byte).',
    '-}',
    '',
];

for (const rom of roms) {
    const hex = readFileSync(join(root, 'tests', 'roms', rom.file)).toString('hex');
    lines.push(`{-| ${rom.comment} -}`, `${rom.name} : String`, `${rom.name} =`, `    "${hex}"`, '');
}

writeFileSync(join(root, 'tests', 'RomData.elm'), lines.join('\n'));
console.log('wrote tests/RomData.elm');
